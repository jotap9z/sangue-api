-- Aplicar no banco sangue antes de iniciar a API atualizada.
-- Migração incremental: não remove tabelas nem registros existentes.
BEGIN;

ALTER TABLE public.hemocentros
    ADD COLUMN IF NOT EXISTS latitude double precision;

ALTER TABLE public.hemocentros
    ADD COLUMN IF NOT EXISTS longitude double precision;

CREATE TABLE IF NOT EXISTS public.api_solicitacoes_exclusao (
    usuario_id bigint PRIMARY KEY REFERENCES public.usuarios(id),
    solicitada_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status varchar(20) NOT NULL DEFAULT 'SOLICITADA'
        CHECK (status IN ('SOLICITADA', 'CONCLUIDA'))
);

CREATE TABLE IF NOT EXISTS public.api_preferencias (
    usuario_id bigint PRIMARY KEY REFERENCES public.usuarios(id),
    avisos_agenda boolean NOT NULL DEFAULT true,
    avisos_emergencia boolean NOT NULL DEFAULT true,
    avisos_mensagens boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.api_recuperacoes_senha (
    token_hash varchar(64) PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES public.usuarios(id),
    senha_hash_origem varchar(255) NOT NULL,
    criada_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em timestamptz NOT NULL,
    utilizada_em timestamptz
);

CREATE INDEX IF NOT EXISTS idx_api_recuperacao_usuario_data
    ON public.api_recuperacoes_senha(usuario_id, criada_em);

CREATE TABLE IF NOT EXISTS public.api_conversas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doador_id bigint NOT NULL REFERENCES public.usuarios(id),
    hemocentro_id bigint NOT NULL REFERENCES public.hemocentros(id),
    criada_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(doador_id, hemocentro_id)
);

CREATE INDEX IF NOT EXISTS idx_api_conversa_centro
    ON public.api_conversas(hemocentro_id, id);

CREATE INDEX IF NOT EXISTS idx_api_conversa_doador
    ON public.api_conversas(doador_id, id);

CREATE TABLE IF NOT EXISTS public.api_mensagens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id bigint NOT NULL REFERENCES public.api_conversas(id),
    remetente_id bigint NOT NULL REFERENCES public.usuarios(id),
    conteudo varchar(2000) NOT NULL
        CHECK (length(trim(conteudo)) BETWEEN 1 AND 2000),
    chave_envio varchar(36) NOT NULL,
    enviada_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(remetente_id, chave_envio)
);

CREATE INDEX IF NOT EXISTS idx_api_mensagem_conversa
    ON public.api_mensagens(conversa_id, id);

CREATE TABLE IF NOT EXISTS public.api_notificacoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES public.usuarios(id),
    evento varchar(120) NOT NULL,
    titulo varchar(150) NOT NULL,
    texto varchar(500) NOT NULL,
    destino varchar(30) NOT NULL,
    referencia_id bigint,
    criada_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lida_em timestamptz,
    UNIQUE(usuario_id, evento)
);

CREATE INDEX IF NOT EXISTS idx_api_notificacao_destinatario
    ON public.api_notificacoes(usuario_id, id);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.hemocentros'::regclass
          AND conname = 'ck_api_coordenadas'
    ) THEN
        ALTER TABLE public.hemocentros
            ADD CONSTRAINT ck_api_coordenadas
            CHECK (
                (latitude IS NULL AND longitude IS NULL)
                OR (
                    latitude IS NOT NULL
                    AND longitude IS NOT NULL
                    AND latitude BETWEEN -90 AND 90
                    AND longitude BETWEEN -180 AND 180
                )
            ) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.api_estoques_sangue'::regclass
          AND conname = 'ck_api_estoque_limites'
    ) THEN
        ALTER TABLE public.api_estoques_sangue
            ADD CONSTRAINT ck_api_estoque_limites
            CHECK (
                quantidade_disponivel BETWEEN 0 AND 1000000
                AND nivel_minimo BETWEEN 1 AND 1000000
                AND nivel_ideal BETWEEN 1 AND 1000000
                AND nivel_ideal > nivel_minimo
                AND versao >= 0
                AND tipo_sanguineo IN (
                    'O+', 'O-', 'A+', 'A-',
                    'B+', 'B-', 'AB+', 'AB-'
                )
            ) NOT VALID;
    END IF;
END;
$$;

-- O QR usa ID escalar no JPA; a integridade também deve existir no banco.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.api_qr_checkin'::regclass
          AND contype = 'f'
          AND confrelid = 'public.api_agendamentos'::regclass
    ) THEN
        ALTER TABLE public.api_qr_checkin
            ADD CONSTRAINT fk_api_qr_agendamento
            FOREIGN KEY (agendamento_id)
            REFERENCES public.api_agendamentos(id)
            NOT VALID;
    END IF;
END;
$$;

-- NOT VALID preserva eventuais dados antigos para conferência;
-- protege novas gravações.
COMMIT;